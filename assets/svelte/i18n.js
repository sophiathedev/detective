export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.has(locale) ? locale : "en"
}

export function translate(locale, message, values = {}) {
  const normalizedLocale = normalizeLocale(locale)
  const template = normalizedLocale === "vi" ? (vi[message] ?? message) : message

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  )
}

export function createI18n(locale = "en") {
  const normalizedLocale = normalizeLocale(locale)

  return Object.freeze({
    locale: normalizedLocale,
    t: (message, values) => translate(normalizedLocale, message, values),
  })
}

export function initializeI18n(locale = "en") {
  const initialLocale = typeof locale === "function" ? locale() : locale
  const i18n = createI18n(initialLocale)
  setContext(I18N_CONTEXT, i18n)
  return i18n
}

export function useI18n() {
  return getContext(I18N_CONTEXT) ?? createI18n()
}
